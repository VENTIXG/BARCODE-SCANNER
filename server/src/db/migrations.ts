/**
 * PostgreSQL schema, applied as ordered migrations. Each runs once, in a transaction; applied
 * versions are kept in schema_migrations.
 *
 * Versions start at 100: 1-4 were the SQLite schema of versions up to 1.2 (legacy/), so a
 * schema number alone tells which kind of database or backup it is.
 *
 * Conventions kept from the SQLite schema, so the queries keep their meaning:
 * timestamps are ISO 8601 text in UTC (ims_now()), yes/no columns are integers 0/1, quantities
 * and prices are double precision. Names compared without regard to case use citext.
 * Foreign keys are DEFERRABLE so a backup can be loaded table by table in any order.
 */
